import {
  applySharpTransforms,
  type AssetTransformQuery,
  canonicalTransformSize,
  decodedAnimationPixels,
  type ImageFit,
  type ImageFormat,
  MAX_ANIMATED_PIXELS,
  resolveOutputFormat,
  sourceEncoderFormat,
} from '../utils/image-transform.js';
import { originalKey, renditionKey } from '../utils/storage-keys.js';

const FORMAT_MIME: Record<string, string> = { webp: 'image/webp', jpeg: 'image/jpeg', png: 'image/png', avif: 'image/avif' };
const FORMAT_EXT: Record<string, string> = { webp: '.webp', jpeg: '.jpg', png: '.png', avif: '.avif' };

/**
 * Two different failures, cached differently: no row means the asset doesn't exist (cache hard);
 * a row without its file (`rowExists`) is an upload in flight (never cache — it's about to appear).
 */
export interface MissingAsset {
  kind: 'missing';
  rowExists: boolean;
}

/** The stored file of an asset and what its response is named and typed after. */
export interface StoredAsset {
  kind: 'found';
  key: string;
  size: number;
  md5: string | null;
  type: string | undefined;
  /** `name` + `extension`. */
  filename: string;
}

/** What the transform route will produce for a request: decided before any read, so a revalidation costs no encode. */
export interface TransformPlan {
  spaceId: string;
  assetId: string;
  key: string;
  size: number;
  md5: string | null;
  name: string;
  assetType: string;
  extension: string;
  metadata: { width?: number; height?: number; pages?: number } | undefined;
  width?: number;
  height?: number;
  quality?: number;
  fit?: ImageFit;
  thumbnail: boolean;
  /** The requested output format, which alone decides the response's type and extension. */
  format?: ImageFormat;
  /** What the pipeline encodes to. */
  encodeAs?: ImageFormat;
  /** Names what the caller asked for (download filename). */
  suffix: string;
  /** Describes the bytes: the effective encode, so equal outputs share a tag and different ones never do. */
  etagSuffix: string;
}

/** The transform route's response: generated bytes (or none, to stream the original), named and typed. */
export type Rendition =
  | { kind: 'bad-request'; message: string }
  | { kind: 'rendition'; output: Buffer | undefined; contentType: string; filename: string };

/** First frame of a video at `time`, as a file in `dir`. */
function extractVideoFrame(videoPath: string, dir: string, time = '00:00:01'): Promise<string> {
  const filename = 'frame.webp';
  return new Promise((resolve, reject) => {
    ffmpeg(videoPath)
      .on('end', () => resolve(join(dir, filename)))
      .on('error', (error: Error) => reject(new Error(`FFmpeg Error: ${error.message}`)))
      .screenshots({ timestamps: [time], filename, folder: dir });
  });
}

/**
 * The three public asset routes (`/assets/:id`, `/original`, `/download`), ported from
 * functions/src/v1/cdn.ts. Every branch keeps its documented behaviour; what changed is the I/O:
 * rows instead of Firestore docs, `StorageDriver` instead of the bucket, a rendition cache instead
 * of relying on the Firebase CDN, streamed passthroughs with Range support, and per-request temp
 * directories (the fixed `/tmp/assets-{id}` names could collide between concurrent requests).
 * The controller turns the decisions made here into the reply.
 */
@Injectable()
export class AssetDeliveryService {
  private readonly logger = new Logger(AssetDeliveryService.name);
  /** LOCALESS_RENDITION_CACHE=disk: generated renditions are stored next to the original and served from there. */
  private readonly cacheRenditions: boolean;

  constructor(
    private readonly assets: AssetsRepository,
    @Inject(STORAGE_DRIVER) private readonly storage: StorageDriver,
    @Inject(APP_CONFIG) config: AppConfig,
  ) {
    if (config.ffmpegPath) ffmpeg.setFfmpegPath(config.ffmpegPath);
    this.cacheRenditions = config.renditionCache === 'disk';
  }

  /**
   * An asset URL with a Firestore id (an asset imported from Firebase, linked from customer sites, CDNs and emails):
   * the asset's UUID, to `301` to, so caches converge on one URL. Undefined when `assetId` is a UUID or no asset has
   * it as `legacy_id`, and the route carries on as usual.
   */
  async findLegacyAssetId(spaceId: string, assetId: string): Promise<string | undefined> {
    if (isUuid(assetId)) return undefined;
    return this.assets.findIdByLegacyId(spaceId, assetId);
  }

  /** `GET /assets/:id/original` and `/download`: the stored bytes, untouched. */
  async findStored(spaceId: string, assetId: string): Promise<StoredAsset | MissingAsset> {
    const key = originalKey(spaceId, assetId);
    const [object, asset] = await Promise.all([this.storage.stat(key), this.assets.findById(spaceId, assetId)]);
    if (!object || !asset) return { kind: 'missing', rowExists: asset !== undefined };
    return {
      kind: 'found',
      key,
      size: object.size,
      md5: asset.md5,
      type: asset.type ?? undefined,
      filename: `${asset.name}${asset.extension ?? ''}`,
    };
  }

  /** Streams a stored object, or the inclusive `range` of it. */
  createReadStream(key: string, range?: ByteRange): Readable {
    return this.storage.createReadStream(key, range);
  }

  /**
   * `GET /assets/:id` (`w`, `h`, `f`, `q`, `fit`, `thumbnail`), before anything is read or transformed: the asset, or
   * `canonical` with the size the source can produce when the request asks for more (one URL, one response).
   */
  async planTransform(
    spaceId: string,
    assetId: string,
    query: AssetTransformQuery,
  ): Promise<MissingAsset | { kind: 'canonical'; query: AssetTransformQuery } | { kind: 'plan'; plan: TransformPlan }> {
    const { quality, fit, thumbnail } = query;
    const key = originalKey(spaceId, assetId);
    const [object, asset] = await Promise.all([this.storage.stat(key), this.assets.findById(spaceId, assetId)]);
    if (!object || !asset) return { kind: 'missing', rowExists: asset !== undefined };
    const assetType = asset.type ?? '';
    const extension = asset.extension ?? '';
    const metadata = (asset.metadata ?? undefined) as { width?: number; height?: number; pages?: number } | undefined;

    // Oversized requests redirect to the size the source can produce: one URL, one response.
    const canonical = canonicalTransformSize(query, { width: metadata?.width, height: metadata?.height });
    if (canonical.width !== query.width || canonical.height !== query.height)
      return { kind: 'canonical', query: { ...query, ...canonical } };
    const { width, height } = canonical;
    const format = resolveOutputFormat({
      requested: query.format,
      sourceType: assetType,
      quality,
      resizing: width !== undefined || height !== undefined,
    });
    // What the pipeline encodes to; `format` alone decides the response's type and extension.
    const encodeAs = format ?? sourceEncoderFormat(assetType);
    // Names what the caller asked for (download filename).
    const suffix = [width ? `w${width}` : '', height ? `h${height}` : '', format ? `f${format}` : '', fit ? `fit${fit}` : '']
      .filter(Boolean)
      .join('-');
    // Describes the bytes: the effective encode, so equal outputs share a tag and different ones never do.
    const etagSuffix = [
      width ? `w${width}` : '',
      height ? `h${height}` : '',
      quality !== undefined ? `q${quality}` : '',
      encodeAs ? `f${encodeAs}` : '',
      fit ? `fit${fit}` : '',
    ]
      .filter(Boolean)
      .join('-');
    return {
      kind: 'plan',
      plan: {
        spaceId,
        assetId,
        key,
        size: object.size,
        md5: asset.md5,
        name: asset.name,
        assetType,
        extension,
        metadata,
        width,
        height,
        quality,
        fit,
        thumbnail,
        format,
        encodeAs,
        suffix,
        etagSuffix,
      },
    };
  }

  /** The bytes of a planned transform: the cached rendition, or generated (and cached), or none to serve the original. */
  async render(plan: TransformPlan): Promise<Rendition> {
    const { spaceId, assetId, key, name, assetType, metadata, width, height, quality, fit, thumbnail, format, encodeAs, suffix } = plan;
    const outputType: string | undefined = format ? FORMAT_MIME[format] : undefined;
    const outputExt: string = format ? FORMAT_EXT[format] : plan.extension;
    let filename = `${name}${plan.extension}`;

    const explicitTransform = width !== undefined || height !== undefined || format !== undefined || thumbnail;
    // Still rasters we can encode are normalised to the encoder's default quality even without parameters.
    const normalisable = sourceEncoderFormat(assetType) !== undefined;

    // Reject an oversized animation from stored metadata before paying for the read. Thumbnails decode one frame.
    if (explicitTransform && !thumbnail && metadata && metadata.pages !== undefined) {
      const storedPixels = decodedAnimationPixels(metadata.width, metadata.height, metadata.pages);
      if (storedPixels > MAX_ANIMATED_PIXELS) {
        return {
          kind: 'bad-request',
          message:
            `Animation is too large to transform: ${metadata.width}x${metadata.height} over ` +
            `${metadata.pages} frames is ${storedPixels} pixels, above the ${MAX_ANIMATED_PIXELS} limit. ` +
            "Request '?thumbnail' for a still frame.",
        };
      }
    }

    const cacheKey = renditionKey(spaceId, assetId, plan.etagSuffix, thumbnail);
    let output: Buffer | undefined;
    let overwriteType: string | undefined;
    // True when `output` was generated (and so belongs in the rendition cache).
    let generated = false;
    /** The cached rendition, or `source()` transformed (only then is the original read). */
    const transform = async (source: () => Sharp | Promise<Sharp>): Promise<Buffer> => {
      if (await this.cachedRendition(cacheKey)) return this.storage.read(cacheKey);
      generated = true;
      return applySharpTransforms(await source(), { width, height, quality, format: encodeAs, fit }).toBuffer();
    };

    if (assetType.startsWith('image/') && (explicitTransform || normalisable)) {
      if (assetType === 'image/webp' || assetType === 'image/gif') {
        // Possibly animated.
        const file = await this.storage.read(key);
        const probe = await sharp(file).metadata();
        const isAnimated = isAnimatedPages(probe.pages);
        if (thumbnail) {
          // An explicit request for a still: collapse to the first frame whatever the source.
          filename = `${name}-${suffix ? `${suffix}-thumbnail` : 'thumbnail'}${outputExt}`;
          output = await transform(() => sharp(file, { page: 0, pages: 1, autoOrient: true }));
          overwriteType = outputType;
        } else if (isAnimated && !explicitTransform) {
          // A bare URL on an animation serves the stored bytes: re-encoding every frame is the most
          // expensive thing this endpoint does, and the pixel budget would make a plain <img> fail.
          output = file;
        } else if (isAnimated) {
          // Resizing decodes every frame at once, so the budget covers the whole animation.
          const frameHeight = probe.pageHeight ?? probe.height ?? 0;
          const decodedPixels = decodedAnimationPixels(probe.width, frameHeight, probe.pages);
          if (decodedPixels > MAX_ANIMATED_PIXELS) {
            return {
              kind: 'bad-request',
              message:
                `Animation is too large to transform: ${probe.width}x${frameHeight} over ${probe.pages} frames is ` +
                `${decodedPixels} pixels, above the ${MAX_ANIMATED_PIXELS} limit. Request '?thumbnail' for a still frame.`,
            };
          }
          if (suffix) filename = `${name}-${suffix}${outputExt}`;
          output = await transform(() => sharp(file, { animated: true, autoOrient: true }));
          overwriteType = outputType;
        } else {
          if (suffix) filename = `${name}-${suffix}${outputExt}`;
          output = await transform(() => sharp(file, { autoOrient: true }));
          overwriteType = outputType;
        }
      } else if (assetType === 'image/svg+xml') {
        // No raster encoder for SVG: served as stored.
      } else {
        // Other images (jpeg, png, tiff, avif, …).
        if (suffix) filename = `${name}-${suffix}${outputExt}`;
        output = await transform(async () => sharp(await this.storage.read(key), { autoOrient: true }));
        overwriteType = outputType;
      }
    } else if (assetType.startsWith('video/') && width !== undefined && thumbnail) {
      overwriteType = format ? FORMAT_MIME[format] : 'image/webp';
      filename = `${name}-${suffix || `w${width}`}-thumbnail${format ? FORMAT_EXT[format] : '.webp'}`;
      if (await this.cachedRendition(cacheKey)) {
        output = await this.storage.read(cacheKey);
      } else {
        output = await this.videoThumbnail(key, { width, height, quality, format: encodeAs, fit });
        generated = true;
      }
    }

    if (output && generated && this.cacheRenditions) {
      // Best effort: a failed cache write must not fail the response.
      await this.storage.put(cacheKey, output).catch(error => this.logger.warn(`Rendition cache write failed for ${cacheKey}: ${error}`));
    }
    return { kind: 'rendition', output, contentType: overwriteType || assetType, filename };
  }

  /** Whether a cached rendition can be served (never, with the cache off: it is generated in the request). */
  private async cachedRendition(cacheKey: string): Promise<boolean> {
    return this.cacheRenditions && (await this.storage.stat(cacheKey)) !== undefined;
  }

  private async videoThumbnail(key: string, options: Parameters<typeof applySharpTransforms>[1]): Promise<Buffer> {
    const dir = await mkdtemp(join(tmpdir(), 'localess-video-'));
    try {
      const videoPath = join(dir, 'source');
      await pipeline(this.storage.createReadStream(key), createWriteStream(videoPath));
      const frame = await extractVideoFrame(videoPath, dir);
      return await applySharpTransforms(sharp(frame, { autoOrient: true }), options).toBuffer();
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  }
}
